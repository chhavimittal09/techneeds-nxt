function createIcon(d, extra = {}) {
  const IconComponent = ({ size = 20, strokeWidth = 2, className = '', ...props }) => (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      {...props}
    >
      {Array.isArray(d) ? d.map((path, idx) => <path key={idx} d={path} />) : <path d={d} />}
      {extra.circle && <circle {...extra.circle} />}
      {extra.polyline && <polyline {...extra.polyline} />}
      {extra.line && <line {...extra.line} />}
    </svg>
  );
  return IconComponent;
}

